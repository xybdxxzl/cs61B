package Arithmetic;

/** 简单的算术类。
 * @author Josh Hug
 * */
public class Arithmetic {

    /** 计算两个 int 的乘积。
     * @param a 值 1
     * @param b 值 2
     * @return a 与 b 的乘积
     * */
    public static int product(int a, int b) {
        return a * b;
    }

    /** 计算两个 int 的和（实现有误）。
     * @param a 值 1
     * @param b 值 2
     * @return a 与 b 的和
     * */
    public static int sum(int a, int b) {
        return a * b;
    }
}
